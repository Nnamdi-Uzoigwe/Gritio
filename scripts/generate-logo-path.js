/* Builds src/features/splash/gritioPath.ts from the Fraunces outlines.
   Run once with: node scripts/generate-logo-path.js */
const fs = require("fs");
const path = require("path");
const opentype = require("opentype.js");

const TEXT = "Gritio";
const FONT_SIZE = 100;
const FONT_PREFIX = "Fraunces_700Bold";

function findFont(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      const found = findFont(full);
      if (found) return found;
    } else if (
      entry.name.startsWith(FONT_PREFIX) &&
      entry.name.endsWith(".ttf")
    ) {
      return full;
    }
  }
  return null;
}

function curveLength(steps, point) {
  let total = 0;
  let prev = point(0);
  for (let i = 1; i <= steps; i++) {
    const next = point(i / steps);
    total += Math.hypot(next.x - prev.x, next.y - prev.y);
    prev = next;
  }
  return total;
}

function pathLength(commands) {
  let total = 0;
  let cx = 0,
    cy = 0,
    sx = 0,
    sy = 0;
  for (const c of commands) {
    if (c.type === "M") {
      cx = sx = c.x;
      cy = sy = c.y;
    } else if (c.type === "L") {
      total += Math.hypot(c.x - cx, c.y - cy);
      cx = c.x;
      cy = c.y;
    } else if (c.type === "C") {
      const x0 = cx,
        y0 = cy;
      total += curveLength(24, (t) => {
        const u = 1 - t;
        return {
          x:
            u * u * u * x0 +
            3 * u * u * t * c.x1 +
            3 * u * t * t * c.x2 +
            t * t * t * c.x,
          y:
            u * u * u * y0 +
            3 * u * u * t * c.y1 +
            3 * u * t * t * c.y2 +
            t * t * t * c.y,
        };
      });
      cx = c.x;
      cy = c.y;
    } else if (c.type === "Q") {
      const x0 = cx,
        y0 = cy;
      total += curveLength(24, (t) => {
        const u = 1 - t;
        return {
          x: u * u * x0 + 2 * u * t * c.x1 + t * t * c.x,
          y: u * u * y0 + 2 * u * t * c.y1 + t * t * c.y,
        };
      });
      cx = c.x;
      cy = c.y;
    } else if (c.type === "Z") {
      total += Math.hypot(sx - cx, sy - cy);
      cx = sx;
      cy = sy;
    }
  }
  return total;
}

const root = path.join(
  __dirname,
  "..",
  "node_modules",
  "@expo-google-fonts",
  "fraunces",
);
const fontPath = findFont(root);
if (!fontPath) {
  console.error("Could not find " + FONT_PREFIX + " .ttf under " + root);
  process.exit(1);
}

// loadSync is deprecated and returns nothing in newer versions, so parse the file directly.
const fileBuffer = fs.readFileSync(fontPath);
const arrayBuffer = fileBuffer.buffer.slice(
  fileBuffer.byteOffset,
  fileBuffer.byteOffset + fileBuffer.byteLength,
);
const font = opentype.parse(arrayBuffer);
if (!font || !font.unitsPerEm) {
  console.error("Could not parse font file: " + fontPath);
  process.exit(1);
}

const scale = FONT_SIZE / font.unitsPerEm;
const glyphs = font.stringToGlyphs(TEXT);

let x = 0;
let minX = Infinity,
  minY = Infinity,
  maxX = -Infinity,
  maxY = -Infinity;
const items = [];

glyphs.forEach((glyph, i) => {
  const p = glyph.getPath(x, 0, FONT_SIZE);
  const box = p.getBoundingBox();
  minX = Math.min(minX, box.x1);
  minY = Math.min(minY, box.y1);
  maxX = Math.max(maxX, box.x2);
  maxY = Math.max(maxY, box.y2);
  items.push({ d: p.toPathData(2), length: Math.ceil(pathLength(p.commands)) });
  x += glyph.advanceWidth * scale;
  const next = glyphs[i + 1];
  if (next) x += font.getKerningValue(glyph, next) * scale;
});

const pad = 4;
const viewBox = {
  x: Math.floor(minX - pad),
  y: Math.floor(minY - pad),
  width: Math.ceil(maxX - minX + pad * 2),
  height: Math.ceil(maxY - minY + pad * 2),
};

const output =
  "// Generated by scripts/generate-logo-path.js. Do not edit by hand.\n" +
  "export const GRITIO_VIEWBOX = " +
  JSON.stringify(viewBox) +
  " as const;\n" +
  "export const GRITIO_GLYPHS: ReadonlyArray<{ d: string; length: number }> = " +
  JSON.stringify(items, null, 2) +
  ";\n";

const target = path.join(
  __dirname,
  "..",
  "src",
  "features",
  "splash",
  "gritioPath.ts",
);
fs.writeFileSync(target, output);
console.log("Wrote " + target + " using " + fontPath);
